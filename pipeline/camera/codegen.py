# -*- coding: utf-8 -*-
"""模式A codegen：spec JSON → 可独立运行的 bpy 脚本（不 import pipeline，可在 Blender 内执行）。

生成脚本职责（任务要求）：
  - 首帧图作**带细分位移平面**：手工网格（N×N 细分 + UV）+ 图像纹理 + Displace 修改器
    （纹理亮度驱动微位移，运镜时产生伪 2.5D 起伏）；
  - 相机动画：spec.camera_track.keys 逐帧 location/rotation_euler/lens 关键帧；
  - 分辨率/帧率/帧域/采样可配（spec.render）；
  - 引擎 EEVEE：双枚举 try/except（4.2–4.5=BLENDER_EEVEE_NEXT，≤4.1 与 5.0+=
    BLENDER_EEVEE，依据设计文档 §2.1 注）；
  - 可选末帧图 crossfade（近平面材质 first→last 逐帧混合）；parallax 运镜自动
    加背景板（更远、放大、压暗的双平面）。

运行方式（由 run_camera.py 或人工）：
  blender --background --python S1.bpy -- --verify-only          # 只建场景并自检（自测用，不渲染）
  blender --background --python S1.bpy -- --render=endpoints    # 渲 start/end 两帧端点图
  blender --background --python S1.bpy -- --render=animation    # 渲整段 PNG 序列（随后 ffmpeg 合 mp4）

对外入口：generate_bpy(spec: dict) -> str
"""

from __future__ import annotations

import json
import os

_MARKER_OK = "SCENE_BUILD_OK"

_TEMPLATE = r'''# -*- coding: utf-8 -*-
# Auto-generated by pipeline.camera.codegen — DO NOT EDIT.
# shot: __SHOT__ | move: __MOVE__ | frames: __FRAMES__ | engine: eevee (dual-enum)
# 用法: blender --background --python this.py -- [--verify-only|--render=endpoints|--render=animation]
import bpy
import json
import os
import sys

SPEC = json.loads("""__SPEC_JSON__""")


def _set_engine(scene):
    """EEVEE 双枚举：4.2-4.5 = BLENDER_EEVEE_NEXT；<=4.1 与 5.0+ = BLENDER_EEVEE。"""
    for enum in ("BLENDER_EEVEE_NEXT", "BLENDER_EEVEE"):
        try:
            scene.render.engine = enum
            return enum
        except Exception:
            continue
    raise RuntimeError("this Blender build has no EEVEE engine")


def _make_grid_mesh(name, half_x, half_y, z, nsub):
    """N x N 细分网格 + UV（U->+X, V->+Y，相机俯视时图像正立）。"""
    n = nsub + 1
    verts = []
    for j in range(n):
        for i in range(n):
            verts.append((-half_x + 2.0 * half_x * i / (n - 1),
                          -half_y + 2.0 * half_y * j / (n - 1),
                          z))
    faces = []
    for j in range(n - 1):
        for i in range(n - 1):
            a = j * n + i
            faces.append((a, a + 1, (j + 1) * n + i + 1, (j + 1) * n + i))
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.validate()
    me.update()
    uv = me.uv_layers.new(name="UVMap")
    if uv is not None:
        for poly in me.polygons:
            for li in poly.loop_indices:
                vi = me.loops[li].vertex_index
                uv.data[li].uv = (vi % n / (n - 1), vi // n / (n - 1))
    return me


def _load_image(path):
    img = bpy.data.images.load(path, check_existing=True)
    img.name = os.path.basename(path)
    return img


def _make_image_material(name, img, tint=1.0):
    """无光照 Emission 材质（关键帧图按原样显示，不搭灯光）。"""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    out = next(n for n in nt.nodes if n.type == "OUTPUT_MATERIAL")
    for n in list(nt.nodes):
        if n.type == "BSDF_PRINCIPLED":
            nt.nodes.remove(n)
    tex = nt.nodes.new("ShaderNodeTexImage")
    tex.image = img
    tex.location = (-620, 200)
    color_src = tex.outputs["Color"]
    if tint < 0.999:
        hsv = nt.nodes.new("ShaderNodeHueSaturation")
        hsv.inputs["Value"].default_value = tint
        hsv.location = (-400, 200)
        nt.links.new(color_src, hsv.inputs["Color"])
        color_src = hsv.outputs["Color"]
    emis = nt.nodes.new("ShaderNodeEmission")
    emis.location = (-200, 200)
    nt.links.new(color_src, emis.inputs["Color"])
    nt.links.new(emis.outputs[0], out.inputs["Surface"])
    return mat, None


def _make_crossfade_material(name, img_first, img_last):
    """first->last 逐帧混合（Mix Shader，Fac 逐帧关键帧）。返回 (mat, mix_node)。"""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    out = next(n for n in nt.nodes if n.type == "OUTPUT_MATERIAL")
    for n in list(nt.nodes):
        if n.type == "BSDF_PRINCIPLED":
            nt.nodes.remove(n)
    mix = nt.nodes.new("ShaderNodeMixShader")
    mix.location = (0, 200)
    ems = []
    for k, img in ((0, img_first), (1, img_last)):
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.image = img
        tex.location = (-820, 200 - 300 * k)
        emis = nt.nodes.new("ShaderNodeEmission")
        emis.location = (-400, 200 - 300 * k)
        nt.links.new(tex.outputs["Color"], emis.inputs["Color"])
        nt.links.new(emis.outputs[0], mix.inputs["Shader" if k == 0 else "Shader_001"])
        ems.append(tex)
    nt.links.new(mix.outputs[0], out.inputs["Surface"])
    return mat, mix


def _add_displace(ob, img, strength):
    """纹理亮度驱动的微位移（伪 2.5D 起伏）。strength 单位=网格单位。"""
    if strength <= 0:
        return None
    tex = bpy.data.textures.new(ob.name + "_disp", type="IMAGE")
    tex.image = img
    mod = ob.modifiers.new("Displace", type="DISPLACE")
    mod.texture = tex
    mod.texture_coords = "UV"
    mod.uv_layer = "UVMap"
    mod.mid_level = 0.5
    mod.strength = strength
    return mod


def build():
    """按 SPEC 构建整场。返回自检信息 dict。"""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    r = SPEC["render"]
    sc = SPEC["scene"]
    out_cfg = SPEC["output"]
    os.makedirs(out_cfg["dir"], exist_ok=True)

    scene.render.resolution_x = int(r["width"])
    scene.render.resolution_y = int(r["height"])
    scene.render.resolution_percentage = 100
    scene.render.fps = int(r["fps"])
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGB"
    scene.frame_start = int(r["frame_start"])
    scene.frame_end = int(r["frame_end"])
    engine = _set_engine(scene)
    try:
        scene.eevee.taa_render_samples = int(r["samples"])
    except Exception:
        pass  # 采样数仅影响渲染质量，不影响场景构建/自检

    half_x, half_y = sc["plane_half"]
    img_first = _load_image(sc["images"]["first"])
    imgs = [img_first]

    has_last = bool(sc["images"].get("last"))
    if has_last:
        imgs.append(_load_image(sc["images"]["last"]))

    # 近平面（首帧图，带细分+位移；有末帧图时改为 crossfade 材质）
    me_near = _make_grid_mesh("PlaneNear", half_x, half_y, 0.0, int(sc["subdivisions"]))
    ob_near = bpy.data.objects.new("PlaneNear", me_near)
    scene.collection.objects.link(ob_near)
    mix_node = None
    if has_last:
        mat, mix_node = _make_crossfade_material("MatNear", img_first, imgs[-1])
        ob_near.data.materials.append(mat)
        _add_displace(ob_near, img_first, float(sc["displacement_strength"]))
    else:
        mat, _ = _make_image_material("MatNear", img_first)
        ob_near.data.materials.append(mat)
        _add_displace(ob_near, img_first, float(sc["displacement_strength"]))

    # 背景板（双平面 2.5D；parallax 运镜自动启用）
    ob_back = None
    bd = sc.get("backdrop") or {}
    if bd.get("enabled") and not has_last:
        b_scale = float(bd["scale"])
        me_back = _make_grid_mesh("PlaneBack", half_x * b_scale, half_y * b_scale,
                                  -float(bd["distance"]), 8)
        ob_back = bpy.data.objects.new("PlaneBack", me_back)
        scene.collection.objects.link(ob_back)
        mat_back, _ = _make_image_material("MatBack", img_first, float(bd["tint"]))
        ob_back.data.materials.append(mat_back)

    # 相机 + 逐帧关键帧
    keys = SPEC["camera_track"]["keys"]
    cam_data = bpy.data.cameras.new("ShotCam")
    cam_data.lens = float(SPEC["camera_track"]["lens"])
    cam_data.sensor_fit = "AUTO"
    cam_data.sensor_width = float(SPEC["camera_track"]["sensor_width"])
    cam = bpy.data.objects.new("ShotCam", cam_data)
    scene.collection.objects.link(cam)
    scene.camera = cam
    for k in keys:
        f = int(k["frame"])
        cam.location = tuple(float(v) for v in k["location"])
        cam.rotation_euler = tuple(float(v) for v in k["rotation"])
        cam_data.lens = float(k["lens"])
        cam.keyframe_insert(data_path="location", frame=f)
        cam.keyframe_insert(data_path="rotation_euler", frame=f)
        cam_data.keyframe_insert(data_path="lens", frame=f)
        if mix_node is not None:
            u = (f - int(r["frame_start"])) / max(1, int(r["frame_end"]) - int(r["frame_start"]))
            mix_node.inputs["Fac"].default_value = u
            mix_node.inputs["Fac"].keyframe_insert("default_value", frame=f)

    return {
        "engine": engine,
        "resolution": [int(r["width"]), int(r["height"])],
        "fps": int(r["fps"]),
        "frames": [int(r["frame_start"]), int(r["frame_end"])],
        "plane_half": [round(half_x, 4), round(half_y, 4)],
        "camera_keys": len(keys),
        "images": [img.name for img in imgs],
        "crossfade": has_last,
        "backdrop": bool(ob_back),
    }


def verify():
    info = build()
    scene = bpy.context.scene
    assert scene.camera is not None, "scene.camera 未设置"
    ob_near = bpy.data.objects.get("PlaneNear")
    assert ob_near is not None, "PlaneNear 缺失"
    dim = ob_near.dimensions
    expect = [2.0 * v for v in info["plane_half"]]
    for got, want in zip((dim.x, dim.y), expect):
        assert abs(got - want) < 1e-2, "平面尺寸异常 %s != %s" % (got, want)
    assert len(SPEC["camera_track"]["keys"]) == info["camera_keys"] >= 2, "关键帧数量异常"
    assert bpy.data.images, "未加载任何图像"
    n_curves = 0
    if cam_anim := scene.camera.animation_data:
        if cam_anim.action:
            n_curves = len(cam_anim.action.fcurves)
    assert n_curves >= 3, "相机动画曲线不足（%d 条）" % n_curves
    info["fcurves"] = n_curves
    print("__MARKER__ " + json.dumps(info))


def _render_endpoints():
    info = build()
    scene = bpy.context.scene
    names = SPEC["output"]["endpoints"]
    frames = (int(SPEC["render"]["frame_start"]), int(SPEC["render"]["frame_end"]))
    written = []
    for frame, name in zip(frames, names):
        scene.frame_set(frame)
        path = os.path.join(SPEC["output"]["dir"], name)
        scene.render.filepath = path
        bpy.ops.render.render(write_still=True)
        written.append(path)
        print("ENDPOINT %d -> %s" % (frame, path))
    print("ENDPOINTS_OK " + json.dumps({"endpoints": written, "build": info}))


def _render_animation():
    info = build()
    scene = bpy.context.scene
    prefix = SPEC["output"]["frame_prefix"]
    scene.render.filepath = os.path.join(SPEC["output"]["dir"], prefix + "_####")
    bpy.ops.render.render(animation=True)
    print("ANIMATION_OK " + json.dumps({
        "dir": SPEC["output"]["dir"], "prefix": prefix,
        "frames": info["frames"], "build": info}))


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    mode = "verify"
    for a in argv:
        if a == "--verify-only":
            mode = "verify"
        elif a.startswith("--render="):
            mode = a.split("=", 1)[1]
    if mode == "verify":
        verify()
    elif mode == "endpoints":
        _render_endpoints()
    elif mode == "animation":
        _render_animation()
    else:
        raise SystemExit("unknown mode: %s" % mode)


if __name__ == "__main__":
    main()
'''


def generate_bpy(spec: dict) -> str:
    """spec dict → bpy 脚本全文（str）。校验 spec 必填结构，失败早报错。"""
    for section in ("render", "scene", "camera_track", "output"):
        if section not in spec:
            raise ValueError("spec 缺 %s 节" % section)
    first = spec["scene"]["images"].get("first")
    if not first or not os.path.isfile(first):
        raise FileNotFoundError("spec.scene.images.first 不存在：%r" % first)
    last = spec["scene"]["images"].get("last")
    if last and not os.path.isfile(last):
        raise FileNotFoundError("spec.scene.images.last 不存在：%r" % last)
    keys = spec["camera_track"].get("keys") or []
    if len(keys) < 2:
        raise ValueError("camera_track.keys 至少 2 帧（endpoints 模式需要首末端点）")

    spec_json = json.dumps(spec, ensure_ascii=True, indent=1)
    if '"""' in spec_json:
        raise ValueError("spec JSON 内含三引号，无法安全嵌入")

    text = (_TEMPLATE
            .replace("__SHOT__", str(spec.get("shot", "?")))
            .replace("__MOVE__", str(spec.get("move", "?")))
            .replace("__FRAMES__", "%d-%d" % (spec["render"]["frame_start"],
                                              spec["render"]["frame_end"])))
    text = text.replace("__SPEC_JSON__", spec_json)
    text = text.replace("__MARKER__", _MARKER_OK)
    return text


def marker() -> str:
    """自测/校验用的场景构建成功标记。"""
    return _MARKER_OK
